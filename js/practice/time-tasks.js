const find = text => ['/', ...text, 'Enter'];
const remove = text => [...find(text), 'd', 'd'];
const line = (text, replacement) => [...find(text), '0', 'c', '$', ...replacement, 'Escape'];
const moveAfter = (text, anchor) => [...remove(text), ...find(anchor), 'p'];
const insertAfter = (anchor, text) => [...find(anchor), 'o', ...text, 'Escape'];
const task = (id, format, initialContent, targetContent, solution) => ({
    id, format, initialContent, targetContent, solution,
    instruction: 'Make the text match the target.',
    highlights: initialContent.filter(text => !targetContent.includes(text)).map(text => ({ line: text, token: null }))
});

